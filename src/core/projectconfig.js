'use strict';

// Projektdatei torvane.yml (auch .torvane.yml, vigil.yml, .vigil.yml) im geprueften Ordner.
// Haelt projektbezogene Einstellungen versionierbar im Repository:
//
//   testDirs: [fixtures, seed-daten]      # Ordner mit reinen Testdaten (Regeln fuer Geheimnisse/Datenschutz abgeschwaecht)
//   vendorDirs: [public/lib]               # mitgelieferter Fremdcode (nur Luecken, keine Stil-/Code-Regeln)
//   generatedDirs: [src/gen]               # erzeugter Code (nur Hinweis)
//   ignore: ["docs/**", "*.snap"]          # wie .vigilignore
//   disabledRules: [quality-long-function]
//   severity: { gha-unpinned-action: info } # Schwere je Regel festlegen
//   qualityRules: true                     # Qualitaetsregeln (lange Funktionen, Kopien) wieder einschalten
//   failOn: high                           # fuer die Kommandozeile/CI
//
// Dazu erkennt classifyUnit erzeugte Dateien und Fremdcode auch ohne Projektdatei.

const fs = require('fs');
const path = require('path');
const { parseYaml } = require('./miniyaml');
const { globToRegExp } = require('./ignore');

const NAMES = ['torvane.yml', '.torvane.yml', 'vigil.yml', '.vigil.yml'];
const SEVERITIES = ['critical', 'high', 'medium', 'low', 'info'];

const list = (v) => (Array.isArray(v) ? v : v == null || v === '' ? [] : [v]).map((x) => String(x).trim()).filter(Boolean);

function normalize(raw, file) {
  const r = raw && typeof raw === 'object' ? raw : {};
  const severity = {};
  if (r.severity && typeof r.severity === 'object') {
    for (const [k, v] of Object.entries(r.severity)) if (SEVERITIES.includes(String(v).toLowerCase())) severity[k] = String(v).toLowerCase();
  }
  return {
    file,
    testDirs: list(r.testDirs || r.testdirs || r.tests),
    vendorDirs: list(r.vendorDirs || r.vendor),
    generatedDirs: list(r.generatedDirs || r.generated),
    ignore: list(r.ignore),
    disabledRules: list(r.disabledRules || r.disable),
    severity,
    qualityRules: r.qualityRules === true || r.quality === true,
    failOn: SEVERITIES.includes(String(r.failOn || '').toLowerCase()) ? String(r.failOn).toLowerCase() : '',
  };
}

// Projektdatei aus einem Ordner lesen; null, wenn keine da ist. Fehler werden als note gemeldet.
function loadProjectConfig(dir) {
  for (const n of NAMES) {
    const p = path.join(dir, n);
    let text;
    try { text = fs.readFileSync(p, 'utf8'); } catch { continue; }
    try { return { ...normalize(parseYaml(text), n), error: null }; }
    catch (e) { return { ...normalize({}, n), error: `${n}: ${e.message}` }; }
  }
  return null;
}

// Mehrere Projektdateien (mehrere Ordner in einer Pruefung) zusammenfuehren
function mergeConfigs(cfgs) {
  const out = normalize({}, '');
  out.files = [];
  for (const c of cfgs.filter(Boolean)) {
    out.files.push(c.file);
    for (const k of ['testDirs', 'vendorDirs', 'generatedDirs', 'ignore', 'disabledRules']) out[k].push(...c[k]);
    Object.assign(out.severity, c.severity);
    if (c.qualityRules) out.qualityRules = true;
    if (c.failOn && (!out.failOn || SEVERITIES.indexOf(c.failOn) < SEVERITIES.indexOf(out.failOn))) out.failOn = c.failOn;
  }
  return out;
}

// --- Erkennung erzeugter Dateien und mitgelieferten Fremdcodes ------------
const GENERATED_NAME = /\.d\.ts$|\.pb\.go$|_pb2(_grpc)?\.py$|\.pb\.(cc|h)$|\.g\.dart$|\.freezed\.dart$|\.generated\.\w+$|\.gen\.\w+$|(^|\/)generated\/|(^|\/)__generated__\/|\.designer\.cs$|\.min\.(js|css)$|\.bundle\.js$|-lock\.json$/i;
const GENERATED_HEAD = /@generated|do not edit|automatically generated|auto-generated|autogenerated|generated by |code generated .* do not edit|this file was generated/i;
const VENDOR_PATH = /(^|\/)(vendor|vendors|third[_-]?party|thirdparty|external|externals|bower_components|jspm_packages|lib\/(?:jquery|bootstrap|angular|react|vue|d3|lodash|moment)[^/]*|static\/(?:js\/)?(?:jquery|bootstrap)[^/]*)(\/|$)/i;
const VENDOR_FILE = /(^|\/)(jquery|bootstrap|angular|react(-dom)?|vue|d3|lodash|underscore|moment|three|chart|highlight|prism|codemirror|ace|pdf|popper|axios|socket\.io|leaflet|swiper|gsap|anime)([.-][\w.]*)?\.js$/i;
const LICENSE_BANNER = /^\s*\/\*[!*][\s\S]{0,400}?(@license|\(c\)|copyright|licensed under|MIT License|Apache License)/i;

function rel(u, root) {
  const l = String(u.label || '').replace(/\\/g, '/');
  return root ? l.replace(new RegExp('^' + root.replace(/[.*+?^${}()|[\]\\]/g, '\\$&') + '/'), '') : l;
}
function inDirs(p, dirs) {
  return dirs.some((d) => {
    const clean = d.replace(/\\/g, '/').replace(/^\.?\//, '').replace(/\/$/, '');
    if (!clean) return false;
    if (/[*?]/.test(clean)) return globToRegExp(clean).test(p) || globToRegExp(clean + '/**').test(p);
    return p === clean || p.startsWith(clean + '/') || p.includes('/' + clean + '/');
  });
}

// Setzt u.devData (Testdaten), u.generated (erzeugt) und u.vendored (Fremdcode). Gibt die Einheit zurueck.
function classifyUnit(u, cfg, root) {
  if (!u || u.kind === 'binary-strings') return u;
  const p = rel(u, root);
  const c = typeof u.content === 'string' ? u.content : '';
  const c0 = c.slice(0, 600);
  if (cfg && inDirs(p, cfg.testDirs)) u.devData = true;
  if ((cfg && inDirs(p, cfg.generatedDirs)) || GENERATED_NAME.test(p) || GENERATED_HEAD.test(c0)) u.generated = true;
  // Fremdcode: Projektangabe, typische Ordner, bekannte Bibliotheken oder Lizenz-Banner + sehr lange Zeilen (minifiziert)
  const minified = c.length > 2000 && c.split('\n', 20).some((l) => l.length > 1500);
  if ((cfg && inDirs(p, cfg.vendorDirs)) || VENDOR_PATH.test(p) || VENDOR_FILE.test(p) || (LICENSE_BANNER.test(c0) && minified)) u.vendored = true;
  return u;
}

module.exports = { loadProjectConfig, mergeConfigs, classifyUnit, NAMES };
